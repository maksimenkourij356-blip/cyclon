export const LEVEL_THRESHOLDS = [
  { points: 0, title: 'Новичок' },
  { points: 600, title: 'Чистюля' },
  { points: 1800, title: 'Хранитель уюта' },
  { points: 3600, title: 'Гуру порядка' },
  { points: 6000, title: 'Легенда чистоты' },
];

export function calculateLevel(points: number): string {
  for (let i = LEVEL_THRESHOLDS.length - 1; i >= 0; i--) {
    if (points >= LEVEL_THRESHOLDS[i].points) {
      return LEVEL_THRESHOLDS[i].title;
    }
  }
  return 'Новичок';
}

export function getNextLevelThreshold(points: number): { nextTitle: string; needed: number; progress: number } {
  for (let i = 0; i < LEVEL_THRESHOLDS.length; i++) {
    if (points < LEVEL_THRESHOLDS[i].points) {
      const prevPoints = i > 0 ? LEVEL_THRESHOLDS[i - 1].points : 0;
      const target = LEVEL_THRESHOLDS[i].points;
      const currentInTier = points - prevPoints;
      const tierSize = target - prevPoints;
      return {
        nextTitle: LEVEL_THRESHOLDS[i].title,
        needed: target - points,
        progress: Math.min(100, Math.round((currentInTier / tierSize) * 100)),
      };
    }
  }
  return { nextTitle: 'Максимальный ранг 🏆', needed: 0, progress: 100 };
}

